/**
 * npm run create-test -- <TEST-ID>
 *
 * Deterministic scaffold for Step 5 (like `npm run create-test` on slide 17):
 * turns a signed-off tracker test into tests/.temp/test-<ID>-<slug>.spec.ts with
 *   - one test() per tracker ID (ID first in the title, tags, tracker annotation)
 *   - tracker steps mapped 1:1 to test.step()
 *   - a dataset JSON next to it when the test is data-driven
 * Every step body THROWS until a human/agent implements it → a scaffold can never pass by accident.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT, loadTests, slugify } from './lib/tracker-lib';

const id = process.argv[2];
if (!id) {
  console.error('Usage: npm run create-test -- <TEST-ID>   e.g. SD-T-301');
  process.exit(1);
}

const test = loadTests().find((t) => t.id === id);
if (!test) {
  console.error(`✖ ${id} not found in tracker/tests`);
  process.exit(1);
}
if (!['Manual', 'Automation In Progress'].includes(test.status)) {
  console.error(
    `✖ ${id} is "${test.status}". Only signed-off tests (Manual / Automation In Progress) may be automated.`,
  );
  process.exit(1);
}

const dir = join(ROOT, 'tests', '.temp');
mkdirSync(dir, { recursive: true });
const slug = slugify(test.title);
const specPath = join(dir, `test-${id}-${slug}.spec.ts`);
if (existsSync(specPath) && !process.argv.includes('--force')) {
  console.error(`✖ ${relative(ROOT, specPath)} already exists (use --force to overwrite)`);
  process.exit(1);
}

const esc = (s: string) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const kind = test.labels.includes('api') ? 'api' : 'ui';
const tags = [...new Set([test.labels.includes('smoke') ? '@smoke' : '@regression', `@${id}`])];
const dataFile = test.dataset ? `test-${id}.data.json` : undefined;

const steps = test.steps
  .map((s, i) => {
    const comment = [
      `// ACTION:   ${s.action}`,
      s.data ? `// DATA:     ${s.data}` : '',
      `// EXPECTED: ${s.expected}`,
    ]
      .filter(Boolean)
      .map((l) => `      ${l}`)
      .join('\n');
    return `    await test.step('${i + 1}. ${esc(s.action)}', async () => {\n${comment}\n      throw new Error('NOT AUTOMATED: step ${i + 1}');\n    });`;
  })
  .join('\n');

const header = `import { test, expect } from '@fixtures';
${dataFile ? `import dataset from './${dataFile}' with { type: 'json' };\n` : ''}
/**
 * ${id} — ${test.title}
 * Story: ${test.story} · Priority: ${test.priority} · Labels: ${test.labels.join(', ')}
 * Precondition: ${test.precondition}
 *
 * GENERATED by scripts/create-test.ts — implement every step, keep step titles 1:1 with the tracker.
 * Reuse page objects from src/pages and fixtures from src/fixtures before writing new code.
 */
`;

const signature = `async ({ ${kind === 'api' ? 'bookingApi' : 'page'} }) => {`;
const body = dataFile
  ? `for (const row of dataset) {
  test(\`${id} ${esc(test.title)} — \${Object.values(row)[0]}\`, {
    tag: ${JSON.stringify(tags).replace(/"/g, "'")},
    annotation: { type: 'tracker', description: '${id}' },
  }, ${signature}
    void row; void expect;
${steps}
  });
}
`
  : `test('${id} ${esc(test.title)}', {
  tag: ${JSON.stringify(tags).replace(/"/g, "'")},
  annotation: { type: 'tracker', description: '${id}' },
}, ${signature}
  void expect;
${steps.replace(/^ {2}/gm, '')}
});
`;

writeFileSync(specPath, header + '\n' + body);
if (dataFile) writeFileSync(join(dir, dataFile), JSON.stringify(test.dataset, null, 2) + '\n');

console.log(`✔ Scaffolded ${relative(ROOT, specPath)}${dataFile ? ` (+ ${dataFile})` : ''}`);
console.log(`  ${test.steps.length} step(s), all throwing NOT AUTOMATED until implemented.`);
console.log(`  Run:  npx playwright test --project=temp ${relative(ROOT, specPath)}`);
